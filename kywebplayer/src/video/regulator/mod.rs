mod clock;

use clock::Clock;

use std::sync::{Arc, Mutex};

use kywasmtime::{sleep_until, Instant};
use tokio::sync::{mpsc, Notify};
use wasm_bindgen::JsValue;

/**
 * A video regulator is a timed buffer.
 *
 * It is used by the client to add some delay before pushing a frame to the
 * video output to compensate for network jitter in order to smooth the
 * playback.
 *
 * It is split into two ends: VideoRegulatorPush and VideoRegulatorPull.
 *
 * When a new video frame is decoded, it is pushed with two timestamps:
 *  - the PTS, time when the frame was generated by the producer
 *  - the received date, time when the packet containing the frame was received
 *    by the client
 *
 * In parallel, the consumer pulls to receive frames ready to be displayed.
 *
 * The goal of the regulator is to preserve as much as possible both the
 * frame interval and a constant end-to-end latency.
 *
 * When a new frame is pushed, its timings (PTS and recv_date) are used to
 * update a clock, which estimates an average offset between the PTS and the
 * received dates.
 *
 * Concretely, this value is used to determine the exact system time when the
 * frame must be passed to the consumer (calling pull()).
 */
struct SharedData {
    clock: Mutex<Clock>,
    notify: Notify,
}

impl SharedData {
    fn new() -> Self {
        Self {
            clock: Mutex::new(Clock::new()),
            notify: Notify::new(),
        }
    }
}

struct Packet<T> {
    object: T,
    pts: u64,
}

pub struct VideoRegulatorPush<T> {
    tx: mpsc::UnboundedSender<Packet<T>>,
    shared_data: Arc<SharedData>,
}

pub struct VideoRegulatorPull<T> {
    delay: u64,
    rx: mpsc::UnboundedReceiver<Packet<T>>,
    shared_data: Arc<SharedData>,
}

impl<T> VideoRegulatorPush<T> {
    fn new(tx: mpsc::UnboundedSender<Packet<T>>, shared_data: Arc<SharedData>) -> Self {
        Self { tx, shared_data }
    }

    // recv_date retrieved by Instant::raw_us()
    pub fn push(&self, object: T, recv_date: u64, pts: u64) -> Result<(), JsValue> {
        {
            let mut clock = self.shared_data.clock.lock().unwrap();
            clock.update(recv_date, pts);
        }
        self.tx.send(Packet { object, pts }).map_err(|_| {
            JsValue::from(js_sys::Error::new(
                "Could not push packet to video regulator",
            ))
        })?;
        self.shared_data.notify.notify_one();

        Ok(())
    }
}

impl<T> VideoRegulatorPull<T> {
    fn new(
        delay: u64,
        rx: mpsc::UnboundedReceiver<Packet<T>>,
        shared_data: Arc<SharedData>,
    ) -> Self {
        Self {
            delay,
            rx,
            shared_data,
        }
    }

    async fn timed_wait(deadline: Instant, notify: &Notify) -> bool {
        tokio::select! {
            _ = sleep_until(deadline) => {
                false
            }
            _ = notify.notified() => {
                true
            }
        }
    }

    pub async fn pull(&mut self) -> Option<T> {
        let Packet { object, pts } = self.rx.recv().await?;

        let clock_range = self.shared_data.clock.lock().unwrap().range;
        assert!(clock_range > 0);
        // if clock.range == 1, then do not wait, pop the first object ASAP
        if clock_range > 1 {
            let call_us = Instant::now().raw_us();
            let max_deadline = call_us + self.delay;

            let mut timed_out = false;
            while !timed_out {
                let system_us = {
                    let clock = self.shared_data.clock.lock().unwrap();
                    clock.to_system_time(pts)
                };
                let deadline_us = std::cmp::min(system_us + self.delay, max_deadline);
                if deadline_us <= call_us {
                    timed_out = true;
                } else {
                    let deadline_instant = Instant::from_raw_us(deadline_us);
                    timed_out = !Self::timed_wait(deadline_instant, &self.shared_data.notify).await;
                }
            }
        }

        Some(object)
    }
}

pub fn create_regulator<T>(delay: u64) -> (VideoRegulatorPush<T>, VideoRegulatorPull<T>) {
    let shared_data = Arc::new(SharedData::new());
    // A push() must never await, it is called from Javascript on_message()
    let (tx, rx) = mpsc::unbounded_channel::<Packet<T>>();
    let push = VideoRegulatorPush::new(tx, shared_data.clone());
    let pull = VideoRegulatorPull::new(delay, rx, shared_data);
    (push, pull)
}
